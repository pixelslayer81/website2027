"""Mirror the Style Shift app's library into the site: one JPEG per index entry
(long edge 1376, like the other page-03 assets) in the app's served order, plus
a classic-script data file the page reads. Usage:
  python -I pages/03-styleshift/assets/build-library.py "<app>/library" pages/03-styleshift
"""
import json
import os
import sys

from PIL import Image

src_dir, page_dir = sys.argv[1], sys.argv[2]
out_dir = os.path.join(page_dir, "assets", "library")
os.makedirs(out_dir, exist_ok=True)

LOOK = {
    "candid": "Candid", "shadows": "Shadows", "pantone_blue": "Pantone Blue",
    "pantone_green": "Pantone Green", "pantone_pink": "Pantone Pink",
}

with open(os.path.join(src_dir, "library.json"), encoding="utf-8") as fh:
    index = json.load(fh)

items = []
for it in index:
    src = os.path.join(src_dir, it["file"])
    if not os.path.exists(src):
        print("skip (no file):", it["id"])
        continue
    im = Image.open(src).convert("RGB")
    w, h = im.size
    im.thumbnail((1376, 1376), Image.LANCZOS)
    dst = os.path.join(out_dir, f"{it['id']}.jpg")
    im.save(dst, format="JPEG", quality=85, optimize=True, progressive=True)
    items.append({
        "id": it["id"],
        "name": it.get("name", "restyle"),
        "look": LOOK.get(it.get("look", ""), it.get("look", "")),
        "favorite": bool(it.get("favorite")),
        "aspect": round(w / h, 4),
    })
    print(it["id"], f"{w}x{h}", "->", im.size, os.path.getsize(dst) // 1024, "KB")

js = (
    "// Page 03 library data: the Style Shift app's library/library.json mirrored\n"
    "// in its served order (newest first), one JPEG per entry in assets/library/.\n"
    "// Generated by the build_library.py scratch script; regenerate, do not hand-edit.\n"
    "// Classic script (no modules): the page opens from file://.\n"
    "window.StyleShiftLibrary = " + json.dumps(items, indent=2, ensure_ascii=False) + ";\n"
)
with open(os.path.join(page_dir, "library-data.js"), "w", encoding="utf-8") as fh:
    fh.write(js)
print(len(items), "items")
